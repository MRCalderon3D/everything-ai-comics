'use strict';
/**
 * Handoff providers (manual, harness-native) share this code. They never
 * call the network: compile() builds a package a person or the harness's own
 * image tool can execute, and generate() returns a record that says where
 * the result goes and what to fill in afterwards.
 */

const {
  checkCapabilities, makeRecord, baseMeta, resolveModel, attachments,
  packageParams, aspectRatioOf,
} = require('./common');

/**
 * prompt package -> handoff request spec. Pure.
 * body.images is the ordered attachment list: position, asset ID, the one
 * role of that image, and its workspace-relative path. body.output is filled
 * by scripts/generate-assets.js with the target render and file path.
 */
function compileHandoff(provider, promptPackage, options, instructions, extraBody = {}) {
  checkCapabilities(promptPackage, provider.capabilities, provider.id);
  const params = packageParams(promptPackage);
  return {
    provider: provider.id,
    kind: provider.kind,
    model: resolveModel(promptPackage, options, provider.id),
    endpoint: null,
    method: null,
    handoff: true,
    body: Object.assign({
      mode: promptPackage.mode || 'generate',
      prompt: promptPackage.prompt,
      negative_prompt: promptPackage.negative_prompt || null,
      aspect_ratio: aspectRatioOf(promptPackage),
      resolution: params.resolution || null,
      images: attachments(promptPackage),
      edit_target: promptPackage.edit_target || null,
      output: { render: null, path: null },
      instructions,
    }, extraBody),
    meta: baseMeta(promptPackage),
  };
}

/**
 * The record for a handoff. Always dry_run, whatever dryRun says: nothing
 * was generated by this call. Model, cost, and seed stay unavailable until
 * the person or the harness completes the record with what the tool reports.
 */
function handoffRecord(requestSpec, who) {
  const meta = requestSpec.meta || {};
  const target = meta.output_path
    ? `Save the result as ${meta.output_path} (never over an existing file).`
    : 'Save the result under the path generate-assets.js prints for this record.';
  return makeRecord(requestSpec, {
    notes: `${who} ${target} Then complete this record: status, media_files, ` +
      'response.summary, and any model, seed, or cost the tool reports. ' +
      'Leave what it does not report as it is; metadata_unavailable lists it. ' +
      'A saved file is a candidate, not a pass: open it and review it before ' +
      'it becomes a reference for the next page.',
  });
}

module.exports = { compileHandoff, handoffRecord };
